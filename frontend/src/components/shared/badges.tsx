import { AlertOctagon, AlertTriangle, ArrowDown, ArrowUp, Bot, CircleDot, FlaskConical, Hand, Minus, Sparkles } from "lucide-react";
import type { ReactNode } from "react";
import { Tooltip } from "@/components/ui/overlay";
import type { ChangeType, Level, Severity, Source } from "@/lib/types";
import { cn, STATUS_LABEL, TEST_TYPE_LABEL } from "@/lib/utils";

export function Chip({ children, className, title }: { children: ReactNode; className?: string; title?: string }) {
  return (
    <span
      title={title}
      className={cn(
        "inline-flex h-[22px] shrink-0 items-center gap-1 whitespace-nowrap rounded-full border px-2 text-[12px] font-medium leading-none [&_svg]:h-3 [&_svg]:w-3",
        className,
      )}
    >
      {children}
    </span>
  );
}

const SOURCE_META: Record<string, { label: string; tip: string; cls: string; icon: ReactNode }> = {
  ai: {
    label: "AI",
    tip: "Generated by the configured AI model.",
    cls: "border-brand/25 bg-brand-soft text-brand-ink",
    icon: <Sparkles />,
  },
  demo: {
    label: "Demo",
    tip: "Generated by the deterministic demo engine (no AI key configured or the AI call failed).",
    cls: "border-demo/25 bg-demo-soft text-demo",
    icon: <FlaskConical />,
  },
  manual: { label: "Manual", tip: "Entered by a person.", cls: "border-line bg-surface-2 text-ink-2", icon: <Hand /> },
  mixed: { label: "AI + Demo", tip: "Partly AI, partly demo engine.", cls: "border-demo/25 bg-demo-soft text-demo", icon: <Bot /> },
};

export function SourceBadge({ source, className }: { source: Source | string; className?: string }) {
  const meta = SOURCE_META[source] ?? SOURCE_META.manual;
  return (
    <Tooltip content={meta.tip}>
      <span tabIndex={0} className="inline-flex">
        <Chip className={cn(meta.cls, className)}>
          {meta.icon}
          {meta.label}
        </Chip>
      </span>
    </Tooltip>
  );
}

const LEVEL_META: Record<string, { cls: string; icon: ReactNode }> = {
  Low: { cls: "border-line text-ink-2 bg-surface", icon: <ArrowDown /> },
  Medium: { cls: "border-line text-ink bg-surface", icon: <Minus /> },
  High: { cls: "border-serious/40 text-ink bg-serious/10", icon: <ArrowUp /> },
  Critical: { cls: "border-critical/40 text-critical bg-critical/10", icon: <AlertOctagon /> },
};

export function LevelBadge({ level, prefix }: { level: Level | string; prefix?: string }) {
  const meta = LEVEL_META[level] ?? LEVEL_META.Medium;
  return (
    <Chip className={meta.cls}>
      {meta.icon}
      {prefix ? `${prefix} ${level.toLowerCase()}` : level}
    </Chip>
  );
}

const SEV_META: Record<string, { cls: string; label: string; bar: string }> = {
  critical: { cls: "border-critical/40 bg-critical/10 text-critical", label: "Critical", bar: "bg-critical" },
  high: { cls: "border-serious/50 bg-serious/10 text-ink", label: "High", bar: "bg-serious" },
  medium: { cls: "border-warning/60 bg-warning/10 text-ink", label: "Medium", bar: "bg-warning" },
  low: { cls: "border-line bg-surface text-ink-2", label: "Low", bar: "bg-ink-3/50" },
  none: { cls: "border-line bg-surface text-ink-3", label: "None", bar: "bg-line" },
};

export function severityBar(sev: string) {
  return (SEV_META[sev] ?? SEV_META.none).bar;
}

export function SeverityBadge({ severity }: { severity: Severity | string }) {
  const meta = SEV_META[severity] ?? SEV_META.none;
  return (
    <Chip className={meta.cls}>
      {severity === "critical" ? <AlertOctagon /> : severity === "high" ? <AlertTriangle /> : <CircleDot />}
      {meta.label}
    </Chip>
  );
}

