export function TestTypeTag({ type }: { type: string }) {
  return <Chip className="border-line bg-surface-2 font-normal text-ink-2">{TEST_TYPE_LABEL[type] ?? type}</Chip>;
}

export function CategoryTag({ category }: { category: string }) {
  return <Chip className="border-line bg-surface font-normal text-ink-2">{category}</Chip>;
}

export function AmbiguityMeter({ score }: { score: number }) {
  const value = Math.round(score * 100);
  const tone = score >= 0.6 ? "bg-critical" : score >= 0.3 ? "bg-warning" : "bg-good";
  const label = score >= 0.6 ? "Ambiguous" : score >= 0.3 ? "Some ambiguity" : "Clear";
  return (
    <span className="inline-flex items-center gap-2" title={`${value}% ambiguity`}>
      <span className="relative h-1.5 w-14 overflow-hidden rounded-full bg-line">
        <span className={cn("absolute inset-y-0 left-0 rounded-full", tone)} style={{ width: `${Math.max(value, 4)}%` }} />
      </span>
      <span className="text-xs text-ink-2">{label}</span>
    </span>
  );
}
